local root=vim.fn.fnamemodify(debug.getinfo(1,'S').source:sub(2),':p:h:h')
vim.opt.rtp:prepend(root)
local fs=require('lilyp.fs')
local app=require('lilyp')
local navigation=require('lilyp.navigation')
local project=fs.stage(fs.snapshot(root..'/tests/fixtures'))
vim.fn.mkdir(project..'/sources','p')
assert(vim.uv.fs_rename(project..'/main.ly',project..'/sources/entry.ly'))
fs.write(project..'/score.yaml',fs.read(project..'/score.yaml'):gsub('main: main.ly','main: sources/entry.ly'))
local source=project..'/sections/refrain.ily'
vim.cmd.edit(vim.fn.fnameescape(source))
local buf=vim.api.nvim_get_current_buf()
app.setup({build_location='project',navigation={enabled=true,python='/obsolete/python',viewer={'/obsolete/pdf-wrapper'}}})
local before=fs.snapshot(project)
local context=navigation.context()
assert(context.source==source and context.main==project..'/sources/entry.ly' and context.manifest==project..'/build/main.svg.json')
assert(not vim.uv.fs_lstat(project..'/build') and vim.deep_equal(before,fs.snapshot(project)))
assert(not app.options().navigation.python and not app.options().navigation.viewer)
local called={}
package.loaded['lilyp.svg_navigation']={open=function(opts)called[#called+1]=opts end,forward=function(opts)called[#called+1]=opts end}
vim.keymap.set('n','<F7>',':echo "existing"<CR>',{buffer=buf})
navigation.attach(buf)
assert(vim.fn.maparg('<F7>','n')==':echo "existing"<CR>')
vim.keymap.del('n','<F7>',{buffer=buf});navigation.attach(buf)
assert(vim.fn.maparg('<F7>','n',false,true).desc=='Locate the source note in the score')
vim.cmd.Viewer();assert(called[1].buf==buf)
app.forward_search({occurrence=2});assert(called[2].occurrence==2)
vim.api.nvim_buf_set_lines(buf,0,0,false,{'% unsaved'})
assert(not pcall(require('lilyp.score_context').assert_clean,context))
vim.cmd('silent edit!');assert(vim.deep_equal(before,fs.snapshot(project)))
assert(not pcall(navigation.open_pdf))
assert(not vim.uv.fs_lstat(project..'/build'))
vim.fn.mkdir(project..'/build','p');fs.write(context.pdf,'publication PDF')
local viewed
app.setup({build_location='project',viewer=function(path)viewed=path end})
navigation.open_pdf();assert(viewed==context.pdf)
assert(vim.deep_equal(before,fs.snapshot(project)))
assert(not pcall(app.setup,{score_viewer={format='pdf'}}))
-- No YAML or Python is needed to resolve a standalone include through the suite.
local standalone=vim.fn.tempname();vim.fn.mkdir(standalone,'p')
local main=standalone..'/score with spaces.ly';fs.write(main,'{ c\'4 }\n')
local part=standalone..'/part.ily';fs.write(part,'part = { c\'4 }\n')
vim.cmd.edit(vim.fn.fnameescape(part))
require('lilyp.integrations.nvls').source_info=function()return {main=main}end
app.setup({python='/missing/python',build_location='project'})
local included=navigation.context()
assert(included.main==main and included.pdf==standalone..'/build/score with spaces.pdf')
assert(not vim.uv.fs_lstat(standalone..'/build'))
navigation.attach(vim.api.nvim_get_current_buf());assert(vim.fn.maparg('<F7>','n')=='')
print('PASS: read-only entry/output resolution, SVG dispatch, unbound shortcuts, dirty-source rejection, plain PDF opening, and inert legacy PDF preferences')
