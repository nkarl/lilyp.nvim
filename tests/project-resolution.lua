local plugin=vim.fs.dirname(vim.fs.dirname(debug.getinfo(1,'S').source:sub(2)))
vim.opt.rtp:prepend(plugin)
vim.opt.rtp:append(vim.fn.stdpath('data')..'/lazy/nvim-lilypond-suite')
vim.o.columns,vim.o.lines=120,40
local fs=require('lilyp.fs')
local resolver=require('lilyp.project')
local root=fs.stage(fs.snapshot(plugin..'/tests/fixtures'))
vim.fn.mkdir(root..'/sources','p')
assert(vim.uv.fs_rename(root..'/main.ly',root..'/sources/entry.ly'))
fs.write(root..'/main.ly','This old entry must not compile.\n')
fs.write(root..'/score.yaml',fs.read(root..'/score.yaml'):gsub('main: main.ly','main: sources/entry.ly'))
local before=fs.snapshot(root)
local resolved=assert(resolver.resolve(root..'/sections/refrain.ily'))
assert(resolved.main==root..'/sources/entry.ly' and resolved.main_relative=='sources/entry.ly')
assert(resolver.resolve(root..'/score.yaml').main==resolved.main)
assert(vim.deep_equal(before,fs.snapshot(root)),'Discovery wrote files')
require('lilyp').setup({})
local suite=require('nvls');suite.setup({})
require('lilyp.build').setup()
vim.cmd.edit(vim.fn.fnameescape(root..'/sections/refrain.ily'));vim.bo.filetype='lilypond'
local file=suite.get_file_infos()
assert(file.main==resolved.main and file.source_folder==root)
local output=require('lilyp.output').directory(root)
assert(file.pdf==output..'/main.pdf' and file.midi==output..'/main.midi')
local config={root_dir=root,init_options={}};local params={}
require('lilyp.lsp').before_init(params,config)
assert(config.init_options.projectMain==file.main)
local s=require('lilyp.session').open(root)
assert(s.main_path=='sources/entry.ly')
s:apply();s:close()
assert(fs.read(root..'/sources/entry.ly')==before['sources/entry.ly'])
assert(fs.read(root..'/main.ly')==before['main.ly'])
local view=require('lilyp.ui').open(root)
assert(view.set('title_size',2));assert(view.apply())
assert(view.session.main_path=='sources/entry.ly' and view.session.values.title_size==2)
view.close()
assert(vim.fn.filereadable(output..'/main.pdf')==1)
local function rejects(text,needle)
  fs.write(root..'/score.yaml',text)
  local ok,err=pcall(resolver.resolve,root)
  assert(not ok and tostring(err):find(needle,1,true),tostring(err))
end
local yaml='kind: lilypond-score\nsource:\n  main: '
rejects(yaml..'../outside.ly\n','escapes')
rejects(yaml..'/tmp/outside.ly\n','relative')
rejects(yaml..'missing.ly\n','does not exist')
rejects('kind: lilypond-score\nsource: [main.ly]\n','mapping')
assert(vim.uv.fs_symlink(root..'/sources/entry.ly',root..'/alias.ly'))
rejects(yaml..'alias.ly\n','Symlink')
-- Missing source uses the same default entry as generated projects.
fs.write(root..'/score.yaml','kind: lilypond-score\n')
assert(resolver.resolve(root).main==root..'/main.ly')
print('PASS: one read-only project resolver for build, LSP, session, Apply/reopen, nested entries, and invalid paths')
