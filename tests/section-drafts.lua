local root=vim.fs.dirname(vim.fs.dirname(debug.getinfo(1,'S').source:sub(2)))
vim.opt.rtp:prepend(root)
local fs=require('lilyp.fs')
local sessions=require('lilyp.session')
local intent=require('lilyp.section_draft')
local function rejects(fn)assert(not pcall(fn),'Invalid draft accepted')end
-- Contracts reject ambiguous variants and malformed payloads at resolution too.
rejects(function()intent.assert_intent('indent',{tag='keep',value=0})end)
rejects(function()intent.assert_intent('indent',{tag='inherit',removed=true})end)
rejects(function()intent.assert_intent('indent',{tag='unknown'})end)
rejects(function()intent.explicit('indent',nil)end)
rejects(function()intent.explicit('indent',false)end)
rejects(function()intent.explicit('paper','a4')end)
local opening={indent=0,hide_tempo_note=false}
local draft=intent.new('aLayout',opening)
opening.indent=1
local source={indent=0,hide_tempo_note=false,lyric_size=2}
local function resolve()return intent.resolve(draft,source,{indent=0,hide_tempo_note=false})end
assert(draft.intents.indent.tag=='keep' and resolve().settings.indent==0)
assert(resolve().settings.lyric_size==nil and resolve().effective.lyric_size==2)
assert(not next(resolve().changed) and not next(resolve().removed))
intent.set(draft,'lyric_size',intent.inherit())
assert(resolve().removed.lyric_size and resolve().effective.lyric_size==nil and resolve().changed.lyric_size)
intent.set(draft,'lyric_size',intent.keep())
assert(resolve().effective.lyric_size==2 and not resolve().changed.lyric_size)
intent.set(draft,'hide_tempo_note',intent.inherit())
assert(resolve().removed.hide_tempo_note and resolve().settings.hide_tempo_note==nil)
intent.set(draft,'hide_tempo_note',intent.explicit('hide_tempo_note',false))
assert(resolve().settings.hide_tempo_note==false and not resolve().removed.hide_tempo_note)
intent.set(draft,'indent',intent.explicit('indent',0))
assert(resolve().settings.indent==0 and draft.intents.indent.tag=='explicit')
intent.set(draft,'chord_size',intent.inherit())
assert(not resolve().removed.chord_size and not resolve().changed.chord_size)
local malformed=vim.deepcopy(draft);malformed.intents.indent=nil
rejects(function()intent.resolve(malformed,source,{})end)
malformed=vim.deepcopy(draft);malformed.intents.indent={tag='explicit',value='invalid'}
rejects(function()intent.resolve(malformed,source,{})end)
local projection=resolve();projection.settings.indent=2
assert(resolve().settings.indent==0,'Projections must not mutate draft state')
local project=fs.stage(fs.snapshot(root..'/tests/fixtures'))
local s=sessions.open(project)
local _,yaml=s:render();s:close();fs.write(project..'/score.yaml',yaml)
local main=fs.read(project..'/main.ly'):gsub('\\layout { \\scoreLayout }',[[\layout { \scoreLayout \context { \Lyrics \override LyricText.font-size = #2 } }]])
fs.write(project..'/main.ly',main)
s=sessions.open(project)
assert(s:view('refrain').values.lyric_size==2)
assert(not s:view('refrain').specified)
s:enable_section('refrain')
assert(s:view('refrain').overrides.lyric_size==2)
s:inherit('refrain','lyric_size')
assert(s:view('refrain').overrides.lyric_size==nil)
assert(s:view('refrain').values.lyric_size==s.draft.lyric_size)
s:set('lyric_size',2,'refrain')
assert(s:view('refrain').overrides.lyric_size==2)
s:set('indent',0,'refrain');s:set('hide_tempo_note',false,'refrain')
local output=s:render_sources()
local persisted=require('lilyp.spec').call({action='read',text=output['score.yaml']}).presentation.sections.refrain.settings
assert(persisted.indent==0 and persisted.hide_tempo_note==false and persisted.lyric_size==2)
s:revert()
assert(not s:view('refrain').specified and s:view('refrain').values.lyric_size==2)
assert(s:render_sources()['main.ly']==main,'Untouched source override must survive')
s:close()
-- Reopening sparse YAML keeps source-only values out of unrelated edits.
local persisted_project=fs.stage(output)
local styling=output['style.ily']:gsub('LyricText.font%-size = #2',function()
  return 'LyricText.font-size = #2 \\override StanzaNumber.font-size = #1'
end)
fs.write(persisted_project..'/style.ily',styling)
s=sessions.open(persisted_project)
assert(s:view('refrain').values.stanza_size==1 and s:view('refrain').overrides.stanza_size==nil)
s:set('indent',1,'refrain')
local unrecorded=s:render_sources()
local declarations=require('lilyp.spec').call({action='read',text=unrecorded['score.yaml']}).presentation.sections.refrain.settings
assert(declarations.stanza_size==nil and unrecorded['style.ily']:find('StanzaNumber.font-size = #1',1,true))
s:keep_section_setting('refrain','indent')
s:inherit('refrain','stanza_size')
assert(s:view('refrain').values.stanza_size==s.draft.stanza_size)
s:keep_section_setting('refrain','stanza_size')
assert(s:view('refrain').values.stanza_size==1)

assert(#s.drift==0 and #s:changes()==0)
s:inherit('refrain','lyric_size');s:keep_section_setting('refrain','lyric_size')
assert(s:view('refrain').values.lyric_size==2 and #s:changes()==0)
s:set('lyric_size',3,'refrain');s:keep_section_setting('refrain','lyric_size')
assert(s:view('refrain').overrides.lyric_size==2 and #s:changes()==0)
s:inherit('refrain','indent');s:inherit('refrain','hide_tempo_note')
s:revert()
assert(s:view('refrain').overrides.indent==0 and s:view('refrain').overrides.hide_tempo_note==false)
assert(#s:changes()==0)
s:close()
local snapshot=fs.snapshot(persisted_project)
vim.o.columns=120;vim.o.lines=40
local ui=require('lilyp.ui').open(persisted_project)
ui.select_scope('refrain');ui.switch_tab(1);ui.selection=1;ui.redraw()
assert(ui.set('staff_size',18));assert(ui.inherit('staff_size'))
assert(ui.undo_setting())
assert(ui.session.section_drafts.refrain.intents.staff_size.tag=='keep')
assert(ui.session:view('refrain').overrides.staff_size==nil)
assert(#ui.session:changes()==0)
ui.close()
assert(vim.deep_equal(snapshot,fs.snapshot(persisted_project)),'Undo/cancel wrote project')
vim.fn.delete(project,'rf');vim.fn.delete(persisted_project,'rf')
print('PASS: section intent contracts, source-only Keep versus Inherit, sparse YAML, false/zero, undo/Revert, projection isolation, and read-only UI')
