local root=vim.fn.fnamemodify(debug.getinfo(1,'S').source:sub(2),':p:h:h')
vim.opt.rtp:prepend(root)
local transpose=require('lilyp.transpose')
local function change(source,selection,target)
  local a,b=assert(source:find(selection,1,true))
  return transpose.transform(source,a,b,target)
end
local function eq(actual,expected) assert(actual==expected,vim.inspect({actual=actual,expected=expected})) end
eq(change("music = { c8 d e g e4 c }",'c8 d e g e4 c',"e"),"music = { e8 fis gis b gis4 e }")
eq(change("music = { c'8 d' e' }","c'8 d' e'",'des\''),"music = { des'8 ees' f' }")
eq(change("music = { c'8 d' e' }","c'8 d' e'",'b'),"music = { b8 cis' dis' }")
eq(change("music = \\relative c' { c8 d e g e4 c d e }",'c8 d e g e4 c',"e'"),"music = \\relative c' { e8 fis gis b gis4 e d e }")
-- The following pitch is repaired even outside the selection, preserving its octave.
eq(change("music = \\relative c' { c4 d e f }",'d e',"b''"),"music = \\relative c' { c4 b'' cis f,, }")
eq(change("music = \\relative c' { <c e g>8 <d f a> r4 c }",'<c e g>8 <d f a>',"d'"),"music = \\relative c' { <d fis a>8 <e g b> r4 c }")
eq(change("music = { \\key g \\major \\time 4/4 c'8~ c'-. r8 \\tuplet 3/2 { d' e' f' } }","c'8~ c'-. r8 \\tuplet 3/2 { d' e' f' }","d'"),"music = { \\key g \\major \\time 4/4 d'8~ d'-. r8 \\tuplet 3/2 { e' fis' g' } }")
local comments="music = { c'4 % c' stays\n %{ outer %{ nested c' %} %} d'4^\"c'\" }"
eq(change(comments,"c'4 % c' stays\n %{ outer %{ nested c' %} %} d'4^\"c'\"","d'"),"music = { d'4 % c' stays\n %{ outer %{ nested c' %} %} e'4^\"c'\" }")
eq(change("music = { c'4 d' }","c'4 d'","c'"),"music = { c'4 d' }")
eq(change("music = \\relative c' { c4-. d8-> e8-- f4-! }",'c4-. d8-> e8-- f4-!',"d'"),"music = \\relative c' { d4-. e8-> fis8-- g4-! }")
local globals="keyAndTime = { \\key g \\major \\time 4/4 }\nglobal = { \\keyAndTime \\tempo 4 = 90 }\nmusic = \\relative c' { \\global c4 d e f }"
eq(change(globals,'c4 d e f',"d'"),globals:gsub('c4 d e f','d4 e fis g'))
local function reject(source,selection,target)
  assert(not pcall(change,source,selection,target or "d'"),'Unexpectedly accepted '..source)
end
reject("music = { cis'4 d' }",'is\'4')
reject("music = { c'4 \\mystery d' }","c'4")
reject("music = \\relative { c4 d }",'c4 d')
reject("music = { << { c'4 } \\\\ { e'4 } >> }","c'4")
reject("words = \\lyricmode { do re mi }",'do re mi')
reject("music = { c'4 #foo d' }","c'4")
reject('\\language "english" music = { c4 d }','c4 d')
reject("music = { c4 d }",'c4 d','c4')
reject("music = { r4 s4 }",'r4 s4')
reject("music = { c4 \\relative c' { d e } }",'c4')
reject("music = { c'4~ c' d' }","c'4")
reject("music = { <c' e'>4~ <c' e'> }","e'>4~ <c'")
reject("music = { c'4= c' }","c'4")
reject("global = { c4 } music = \\relative c' { \\global d e }",'d e')
reject("global = { \\global } music = { \\global c4 }",'c4')

-- Public API: unsaved source, exact end-exclusive ranges, boundary repair, undo.
local buf=vim.api.nvim_create_buf(true,false);vim.api.nvim_set_current_buf(buf)
local original="music = \\relative c' { c4 d e f }"
local saved=vim.fn.tempname()..'.ily'
vim.fn.writefile({original},saved)
vim.api.nvim_buf_set_name(buf,saved)
vim.api.nvim_buf_set_lines(buf,0,-1,false,{original})
vim.cmd('let &undolevels = &undolevels')
local a,b=original:find('d e',1,true)
local info=require('lilyp').transpose("b''",{start={0,a-1},finish={0,b}})
eq(info.semitones,21);eq(info.notes,2)
eq(vim.api.nvim_buf_get_lines(buf,0,-1,false)[1],"music = \\relative c' { c4 b'' cis f,, }")
assert(vim.bo[buf].modified)
eq(table.concat(vim.fn.readfile(saved),'\n'),original)
vim.cmd('undo');eq(vim.api.nvim_buf_get_lines(buf,0,-1,false)[1],original)
vim.cmd('redo')
local before=vim.api.nvim_buf_get_lines(buf,0,-1,false)
assert(not pcall(require('lilyp').transpose,'invalid',{start={0,0},finish={0,1}}))
eq(vim.api.nvim_buf_get_lines(buf,0,-1,false)[1],before[1])
-- Last characterwise selection, reversed active selection, and linewise marks.
vim.api.nvim_buf_set_lines(buf,0,-1,false,{"music = { c'4 d'4 }"})
vim.api.nvim_win_set_cursor(0,{1,10});vim.cmd('normal! v5l')
require('lilyp').transpose("d'")
eq(vim.api.nvim_buf_get_lines(buf,0,-1,false)[1],"music = { d'4 e'4 }")
vim.cmd('normal! '..vim.api.nvim_replace_termcodes('<Esc>',true,false,true))
-- A reversed selection uses Neovim's native region semantics.
vim.api.nvim_buf_set_lines(buf,0,-1,false,{"music = { c'4 d'4 }"})
vim.api.nvim_win_set_cursor(0,{1,15});vim.cmd('normal! v5h')
require('lilyp').transpose("d'")
eq(vim.api.nvim_buf_get_lines(buf,0,-1,false)[1],"music = { d'4 e'4 }")
vim.cmd('normal! '..vim.api.nvim_replace_termcodes('<Esc>',true,false,true))
-- Last Visual selection works after leaving Visual mode (e.g. :lua invocation).
vim.api.nvim_buf_set_lines(buf,0,-1,false,{"music = { c'4 d'4 }"})
vim.api.nvim_win_set_cursor(0,{1,10});vim.cmd('normal! v5l')
vim.cmd('normal! '..vim.api.nvim_replace_termcodes('<Esc>',true,false,true))
require('lilyp').transpose("d'")
eq(vim.api.nvim_buf_get_lines(buf,0,-1,false)[1],"music = { d'4 e'4 }")
-- Linewise selection of a complete expression; indentation/newlines stay intact.
vim.api.nvim_buf_set_lines(buf,0,-1,false,{"  music = \\relative c' { c4 d }  ","other = { e4 }"})
vim.api.nvim_win_set_cursor(0,{1,0});vim.cmd('normal! V')
require('lilyp').transpose("d'")
eq(vim.api.nvim_buf_get_lines(buf,0,-1,false)[1],"  music = \\relative c' { d4 e }  ")
eq(vim.api.nvim_buf_get_lines(buf,0,-1,false)[2],"other = { e4 }")
vim.cmd('normal! '..vim.api.nvim_replace_termcodes('<Esc>',true,false,true))
-- Exclusive selection and multiline byte coordinates.
vim.o.selection='exclusive'
vim.api.nvim_buf_set_lines(buf,0,-1,false,{"music = { c'4 d'4 }"})
vim.api.nvim_win_set_cursor(0,{1,10});vim.cmd('normal! v6l')
require('lilyp').transpose("d'")
eq(vim.api.nvim_buf_get_lines(buf,0,-1,false)[1],"music = { d'4 e'4 }")
vim.cmd('normal! '..vim.api.nvim_replace_termcodes('<Esc>',true,false,true))
vim.o.selection='inclusive'
vim.api.nvim_buf_set_lines(buf,0,-1,false,{"music = { c'4 d'4 }"})
vim.api.nvim_win_set_cursor(0,{1,10});vim.cmd('normal! '..vim.api.nvim_replace_termcodes('<C-v>',true,false,true)..'5l')
assert(not pcall(require('lilyp').transpose,"d'"),'Blockwise selection should fail')
eq(vim.api.nvim_buf_get_lines(buf,0,-1,false)[1],"music = { c'4 d'4 }")
vim.cmd('normal! '..vim.api.nvim_replace_termcodes('<Esc>',true,false,true))
vim.api.nvim_buf_set_lines(buf,0,-1,false,{"music = \\relative c' {",'  c8 % tiếng Việt','  d e g','  c4','}'})
require('lilyp').transpose("d'",{start={1,2},finish={2,7}})
eq(table.concat(vim.api.nvim_buf_get_lines(buf,0,-1,false),'\n'),"music = \\relative c' {\n  d8 % tiếng Việt\n  e fis a\n  c4\n}")
print('PASS: literal pitch transposition, relative/chord context, formatting, refusals, selection API, and undo')
